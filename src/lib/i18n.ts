export function getExerciseDisplayName(
  exercise: { nameTr?: string | null; nameEn?: string | null },
  lang: Language
): string {
  if (lang === 'tr') {
    return exercise.nameTr || exercise.nameEn || '';
  }
  // İngilizce, Almanca ve İspanyolca için uluslararası standart egzersiz adı (nameEn)
  return exercise.nameEn || exercise.nameTr || '';
}

export function getEquipmentDisplayName(equipment: string, lang: Language): string {
  const norm = equipment?.toLowerCase().trim() || '';
  return EQUIPMENT_TRANSLATIONS[lang]?.[norm] || EQUIPMENT_TRANSLATIONS.en[norm] || equipment;
}

export function getMuscleDisplayName(muscle: string, lang: Language): string {
  const norm = muscle?.toLowerCase().replace(/\s+/g, '_').trim() || '';
  return MUSCLE_TRANSLATIONS[lang]?.[norm] || MUSCLE_TRANSLATIONS.en[norm] || muscle.replace('_', ' ');
}
